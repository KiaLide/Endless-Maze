# 第 1 層標準怪物
BASE = dict(hp=50, atk=4, def_=4, spd=9, crit=5, eva=3)

def floor_mult(f):
    """生命、攻擊、防禦的樓層倍率：第 1～40 層每層 ×1.06，第 41～50 層每層 ×1.03，第 51 層起每層 ×1.05"""
    return 1.06 ** (min(f, 40) - 1) * 1.03 ** max(0, min(f, 50) - 40) * 1.05 ** max(0, f - 50)

def speed_mult(f):
    return 1.01 ** (f - 1)

# 類型倍率：生命、攻擊、防禦、速度、閃避加成
