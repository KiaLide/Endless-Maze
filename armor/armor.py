if __name__ == '__main__':
    catalog = []
    for sid, sname, kind, focus, fn, names in SETS:
        assert len(names) == 20, sid
        for t in range(1, 21):
            catalog.append(dict(set_id=sid, set_name=sname, type=kind, focus=focus, tier=t, name=names[t - 1],
                                material=MATS[t - 1], rarity=rarity(t),
                                stats={k: v for k, v in fn(t, GROW ** (t - 1)).items() if v != 0}))
    with open(os.path.join(OUT, 'armor.json'), 'w', encoding='utf-8') as f:
        json.dump(catalog, f, ensure_ascii=False, indent=1)
    print(len(catalog), 'pieces')
