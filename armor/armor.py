"""產生 armor.json：6 套防具 × 20 階，每套側重一種能力值。

用法：python3 armor/armor.py
"""
import json, os

OUT = os.path.dirname(os.path.abspath(__file__))
GROW = 1.17   # 生命、防禦、攻擊類數值的每階成長

# 與武器共用的 20 階材質與稀有度
MATS = ['木', '青銅', '鐵', '鋼', '精鋼', '白銀', '王國', '黑鐵', '秘銀', '烈焰',
        '霜寒', '雷鳴', '翠玉', '黃金', '暗影', '聖光', '龍', '星辰', '混沌', '神']
RARITY = [(1, 4, '普通'), (5, 8, '優良'), (9, 12, '稀有'), (13, 16, '史詩'), (17, 19, '傳說'), (20, 20, '神話')]

def rarity(t):
    for a, b, n in RARITY:
        if a <= t <= b: return n

def pct(x):   # 爆擊率、閃避（%）取到 0.5
    return round(x * 2) / 2

